import re
import sys

# Valid autobadge values: auto, +N, -N
VALID_AUTOBADGE = re.compile(r'^(auto|[+-][\d]+)$')


PY2 = sys.version_info[0] == 2

if not PY2:
    string_types = (str,)
else:
    string_types = (str, unicode)


def _set_if_not_none(payload, key, value):
    if value is not None:
        payload[key] = value


def notification(alert=None, ios=None, android=None, winphone=None, hmos=None,
                 quickapp=None, voip=None):
    """Create a notification payload.

    :keyword alert: A simple text alert, applicable for all platforms.
    :keyword ios: An iOS platform override, as generated by :py:func:`ios`.
    :keyword android: An Android platform override, as generated by :py:func:`android`.
    :keyword winphone: A MPNS platform override, as generated by :py:func:`mpns`.
    :keyword hmos: A hmos platform override, as generated by :py:func:`hmos`.
    :keyword quickapp: A quickapp platform override, as generated by :py:func:`quickapp`.
    :keyword voip: An iOS VOIP payload dict (opaque key/value pairs).

    """
    payload = {}
    _set_if_not_none(payload, 'alert', alert)
    _set_if_not_none(payload, 'ios', ios)
    _set_if_not_none(payload, 'android', android)
    _set_if_not_none(payload, 'winphone', winphone)
    _set_if_not_none(payload, 'hmos', hmos)
    _set_if_not_none(payload, 'quickapp', quickapp)
    _set_if_not_none(payload, 'voip', voip)
    if not payload:
        raise ValueError("Notification body may not be empty")
    return payload


def ios(alert=None, badge='+1', sound=None, content_available=False,
        mutable_content=False, category=None, extras=None, sound_disable=False,
        thread_id=None, interruption_level=None):
    """iOS/APNS specific platform override payload.

    :keyword alert: iOS format alert, as either a string or dictionary.
    :keyword badge: An integer badge value or an *autobadge* string.
    :keyword sound: An string sound file to play.
    :keyword content_available: If True, pass on the content-available command
        for Newsstand iOS applications.
    :keyword extras: A set of key/value pairs to include in the push payload
        sent to the device.
    :keyword sound_disalbe: Disable sound to implement slient push.
    :keyword mutable_content: If True, enables modifying notification content in iOS service extension.
    :keyword category: String category for iOS notification action buttons.
    :keyword thread_id: String identifier to group related notifications in iOS.
    :keyword interruption_level: iOS 15+ interruption level
        (``active`` / ``critical`` / ``passive`` / ``time-sensitive``).

    >>> ios(alert='Hello!', sound='cat.caf',
    ...     extras={'articleid': '12345'})
    {'sound': 'cat.caf', 'extras': {'articleid': '12345'}, 'alert': 'Hello!'}

    """
    payload = {}
    if alert is not None:
        if not isinstance(alert, (string_types, dict)):
            raise ValueError("iOS alert must be a string or dictionary")
        payload['alert'] = alert
    if badge is not None:
        if not (isinstance(badge, str) or isinstance(badge, int)):
            raise ValueError("iOS badge must be an integer or string")
        if isinstance(badge, str) and not VALID_AUTOBADGE.match(badge):
            raise ValueError("Invalid iOS autobadge value")
        payload['badge'] = badge
    if not sound_disable:
        if sound is not None:
            payload['sound'] = sound
        else:
            payload['sound'] = 'default'
    if content_available:
        payload['content-available'] = 1
    if mutable_content:
        payload['mutable-content'] = 1
    if category:
        payload['category'] = category
    if thread_id:
        payload['thread-id'] = thread_id
    if interruption_level is not None:
        allowed = ('active', 'critical', 'passive', 'time-sensitive')
        if interruption_level not in allowed:
            raise ValueError(
                "iOS interruption_level must be one of %s" % (allowed,)
            )
        payload['interruption-level'] = interruption_level
    if extras is not None:
        payload['extras'] = extras
    return payload


