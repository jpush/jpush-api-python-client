def quickapp(alert, title, page, extras=None):
    """QuickApp platform notification payload.

    more info:https://docs.jiguang.cn/jpush/server/push/rest_api_v3_push#quickapp
    """
    payload = {
        'alert': alert,
        'title': title,
        'page': page,
    }
    if extras is not None:
        payload['extras'] = extras
    return payload


def voip(payload):
    """iOS VOIP notification payload (opaque key/value pairs).

    more info:https://docs.jiguang.cn/jpush/server/push/rest_api_v3_push#voip
    """
    if not isinstance(payload, dict):
        raise ValueError("voip payload must be a dictionary")
    return payload


def message(msg_content, title=None, content_type=None, extras=None):
    """Inner-conn push message payload creation.

    :param msg_content: Required, string
    :param title: Optional, string
    :keyword content_type: Optional, MIME type of the body
    :keyword extras: Optional, dictionary of string values.

    """
    payload = {
        'msg_content': msg_content,
    }
    if title is not None:
        payload['title'] = title
    if content_type is not None:
        payload['content_type'] = content_type
    if extras is not None:
        payload['extras'] = extras
    return payload

